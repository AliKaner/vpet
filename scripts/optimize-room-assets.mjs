import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

// Keep source PNGs intact. Content-addressed filenames safely support immutable caching.
const sources = { base:'public/assets/pets/room-isometric-v2.png', themes:'public/assets/pets/room-themes-v1.png', styles:'public/assets/pets/room-styles-v1.png', garden:'public/assets/pets/room-garden-v1.png', hobbies:'public/assets/pets/room-hobbies-v1.png', living:'public/assets/pets/room-living-v1.png' };
await mkdir('public/assets/room',{recursive:true});
for(const name of ['essentials','studio','nature','enchanted','workshop']) sources[name]=`public/assets/pets/room-${name}-v1.png`;
const urls = {};
for (const [name,path] of Object.entries(sources)) {
  const source=await readFile(path);
  const output=await sharp(source).resize({width:1024,withoutEnlargement:true,kernel:'nearest'}).webp({quality:82,alphaQuality:100,effort:6}).toBuffer();
  const hash=createHash('sha256').update(output).digest('hex').slice(0,12);
  const url=`/assets/room/${name}-${hash}.webp`;
  await writeFile(`public${url}`,output);
  urls[name]=url;
  console.log(`${name}: ${source.length} -> ${output.length} bytes (${Math.round((1-output.length/source.length)*100)}% smaller)`);
}
await writeFile('src/components/room/roomAssetUrls.ts',`// Generated by npm run assets:room. Do not edit URLs manually.\nexport const ROOM_ATLASES = ${JSON.stringify(urls,null,2)} as const;\n`);
for (const page of ['index.html','room-preview.html']) {
  let html=await readFile(page,'utf8');
  html=html.replace(/\s*<link[^>]*data-room-atlas[^>]*>/g,'');
  // Expansion sets load only when displayed; keep the initial four-sheet budget stable.
  const links=Object.values(urls).slice(0,4).map(url=>`    <link data-room-atlas rel="preload" as="image" type="image/webp" href="${url}" fetchpriority="high" />`).join('\n');
  html=html.replace('</head>',`${links}\n  </head>`);
  await writeFile(page,html);
}
